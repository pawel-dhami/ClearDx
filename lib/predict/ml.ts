const SEVERITY_SCALE = { mild: 0.75, moderate: 1, severe: 1.25 } as const;
const FOLLOW_UP = /^Do you also have (.+)\?$/;

/** Dataset feature indices for a symptom: catalog mapping first, then an exact dataset name (e.g. typed in "your own words"). */
function featuresFor(text: string): number[] {
  const known = findSymptom(text);
  const names = known ? (FEATURE_MAP[known.id] ?? []) : [text];
  return names.map((n) => FEATURE_INDEX.get(n.toLowerCase())).filter((i): i is number => i !== undefined);
}

/** The dataset has no severity labels; this keyword list is a conservative triage hint, defaulting to "moderate". */
const SEVERITY_RULES: [RegExp, Severity][] = [
  [/heart attack|myocardial|stroke|meningitis|sepsis|septic|pulmonary embol|aortic|anaphyla|appendicitis|ectopic|subarachnoid|intracranial|cardiac arrest|pneumothorax|peritonitis|diabetic ketoacidosis|encephalitis|tension pneumothorax/, "emergency"],
  [/pneumonia|cancer|carcinoma|lymphoma|leukemia|tumor|failure|hepatitis|pancreatitis|cirrhosis|tuberculosis|embol|thrombo|infarct|bleed|hemorrhage|kidney stone|pyelonephritis|cholecystitis|diverticulitis|seizure|sickle|lupus|endocarditis|malaria|dengue|fracture/, "high"],
  [/common cold|allergy|allergic|acne|wart|dermatitis|eczema|dandruff|conjunctivitis|sinusitis|pharyngitis|laryngitis|strain|sprain|insect bite|ingrown|corn|callus|sunburn|gastritis|tension headache/, "low"],
];
const severityOf = (disease: string): Severity => SEVERITY_RULES.find(([re]) => re.test(disease))?.[1] ?? "moderate";

const display = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const round2 = (n: number) => Math.round(n * 100) / 100;
/** Log-odds weights → the app's -1…1 contribution scale. */
const toUnit = (w: number) => round2(Math.tanh(w / 4));

export function mlPredict(input: PredictInput): PredictionResult {
  const allAnswers = input.answers ?? [];
  const details = parseDetailAnswers(allAnswers);
  const answers = allAnswers.filter((a) => !isDetailAnswer(a));

  // ---------- encode ----------
  const x = new Map<number, number>(); // feature index → value
  const bySymptom = new Map<string, number[]>(); // user text → feature indices
  const unmapped: string[] = [];
  for (const text of input.symptoms) {
    const idx = featuresFor(text);
    if (!idx.length) {
      unmapped.push(text);
      continue;
    }
    bySymptom.set(text, idx);
    const sev = details.get(text.toLowerCase())?.severity;
    for (const i of idx) x.set(i, Math.max(x.get(i) ?? 0, sev ? SEVERITY_SCALE[sev] : 1));
  }
  // "Yes" to a model follow-up ("Do you also have X?") adds that symptom.
  const added: string[] = [];
  for (const a of answers) {
    const m = FOLLOW_UP.exec(a.question);
    const i = m ? FEATURE_INDEX.get(m[1].toLowerCase()) : undefined;
    if (i === undefined || !/^(y|yes|true)\b/i.test(a.answer)) continue;
    if (!x.has(i)) added.push(M.features[i]);
    x.set(i, 1);
  }

  // ---------- score every disease ----------
  const logits = M.intercept.map((b, c) => {
    let z = b;
    const w = M.weights[c];
    for (const [i, v] of x) z += (w[i] ?? 0) * v;
    return z;
  });
  const max = Math.max(...logits);
  const exp = logits.map((z) => Math.exp(z - max));
  const sum = exp.reduce((a, b) => a + b, 0);
  const probs = exp.map((e) => e / sum);
  const order = probs.map((p, c) => [p, c] as const).sort((a, b) => b[0] - a[0]);
  const top = order.slice(0, 4);

  const predictions: Prediction[] = top.map(([p, c]) => {
    const disease = M.classes[c];
    const contributions: Contribution[] = [];
    for (const [text, idx] of bySymptom) {
      const w = idx.reduce((acc, i) => acc + (M.weights[c][i] ?? 0) * (x.get(i) ?? 0), 0);
      if (Math.abs(w) < 0.05) continue;
      const names = idx.map((i) => M.features[i]).join(", ");
      contributions.push({
        symptom: text,
        weight: toUnit(w),
        reason: `In the training data, "${names}" ${w > 0 ? "raises" : "lowers"} the odds of ${disease} (log-odds ${w > 0 ? "+" : "−"}${Math.abs(w).toFixed(2)}).`,
      });
    }
    contributions.sort((a, b) => Math.abs(b.weight) - Math.abs(a.weight));
    return { condition: display(disease), confidence: round2(Math.min(0.95, Math.max(0.01, p))), severity: severityOf(disease), contributions };
  });

  // ---------- red flags (same rules as the built-in engine) ----------
  const present = new Set(input.symptoms.map((t) => findSymptom(t)?.id).filter((v): v is string => !!v));
  const red_flags = RED_FLAG_RULES.filter((r) => r.when(present, input)).map((r) => r.text);

  // ---------- follow-ups: symptoms that best separate the top two ----------
  const [a, b] = [top[0]?.[1], top[1]?.[1]];
  const asked = new Set(answers.map((q) => q.question));
  const follow_up_questions: FollowUpQuestion[] = [];
  if (a !== undefined && b !== undefined) {
    const candidates = new Set([...Object.keys(M.weights[a]), ...Object.keys(M.weights[b])].map(Number));
    [...candidates]
      .filter((i) => !x.has(i))
      .map((i) => ({ i, d: (M.weights[a][i] ?? 0) - (M.weights[b][i] ?? 0) }))
      .sort((p, q) => Math.abs(q.d) - Math.abs(p.d))
      .forEach(({ i, d }) => {
        const question = `Do you also have ${M.features[i]}?`;
        if (follow_up_questions.length >= 3 || asked.has(question)) return;
        const [up, down] = d > 0 ? [M.classes[a], M.classes[b]] : [M.classes[b], M.classes[a]];
        follow_up_questions.push({ question, why_it_matters: `In the training data this points toward ${up} rather than ${down}.` });
      });
  }

  // ---------- reasoning ----------
  const used = input.symptoms.length - unmapped.length;
  const steps: string[] = [
    `Matched ${used} of ${input.symptoms.length} symptom${input.symptoms.length === 1 ? "" : "s"} to the model's ${M.features.length}-symptom vocabulary` +
      (unmapped.length ? `; ${unmapped.join(", ")} ${unmapped.length === 1 ? "has no counterpart and carries" : "have no counterpart and carry"} no weight.` : "."),
    `Scored all ${M.classes.length} diseases with a logistic-regression model trained on 246,945 synthetic cases (Mendeley "Disease and symptoms dataset 2023").`,
  ];
  if (details.size) steps.push(`Scaled symptoms by the severity you logged (mild ×0.75, severe ×1.25).`);
  if (added.length) steps.push(`Added symptoms you confirmed in follow-ups: ${added.join(", ")}.`);
  const strongest = predictions.flatMap((p) => p.contributions.map((c) => ({ c, p }))).sort((u, v) => v.c.weight - u.c.weight)[0];
  if (strongest) steps.push(`Strongest single signal: "${strongest.c.symptom}" toward ${strongest.p.condition} (weight +${strongest.c.weight.toFixed(2)}).`);
  steps.push(`Age, sex and duration are not in the training data, so they do not change this model's ranking.`);
  const [first, second] = predictions;
  if (first)
    steps.push(
      second
        ? `Top result: ${first.condition} at ${Math.round(first.confidence * 100)}%, ${Math.round((first.confidence - second.confidence) * 100)} points ahead of ${second.condition}.`
        : `Top result: ${first.condition} at ${Math.round(first.confidence * 100)}%.`,
    );
  if (first) {
    const note = reliabilityNote(top[0][0]);
    if (note) steps.push(note);
  }
  if (red_flags.length) steps.push("Red-flag symptoms were detected; these warrant medical attention regardless of the ranking.");

  return { predictions, reasoning_steps: steps, red_flags, follow_up_questions };
}

export class MlPredictor implements Predictor {
  readonly source = "ml" as const;
  async predict(input: PredictInput): Promise<PredictionResult> {
    return mlPredict(input);
  }
}
