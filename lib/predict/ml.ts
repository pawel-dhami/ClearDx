import { findSymptom } from "@/lib/symptoms";
import { isDetailAnswer, parseDetailAnswers } from "@/lib/symptomDetail";
import { RED_FLAG_RULES } from "./mock";
import type { Predictor } from "./predictor";
import type { Contribution, FollowUpQuestion, PredictInput, Prediction, PredictionResult, Severity } from "./types";
import model from "./model/disease-model.json";
import verification from "./model/verification.json";

/**
 * Predictor backed by a model trained on public data (see ml/train.py and the /model page):
 * multinomial logistic regression over 377 symptoms and 773 diseases from the
 * "Disease and symptoms dataset 2023" (Mendeley Data, CC BY 4.0).
 *
 * It returns the same shape as the other predictors. Each contribution is the model's
 * own weight for that symptom and disease, so the explanation is exact, not a summary.
 * Opt-in: set PREDICTOR=ml.
 */

interface ExportedModel {
  features: string[];
  classes: string[];
  intercept: number[];
  weights: Record<string, number>[];
}
const M = model as unknown as ExportedModel;

/** Calibration from ml/verify.py: how often the top pick was right, per confidence band, on unseen test cases. */
const CAL = verification.calibration.bins;
const HOLDOUT_CASES = verification.holdout.cases;
function reliabilityNote(confidence: number): string | null {
  const bin = CAL.find((b) => confidence >= b.from && (confidence < b.to || b.to === 1));
  if (!bin || bin.cases < 50) return null;
  return `Verification: on ${HOLDOUT_CASES.toLocaleString("en-GB")} unseen test cases, when the top match scored ${Math.round(bin.from * 100)}–${Math.round(bin.to * 100)}% it was the right disease ${Math.round(bin.accuracy * 100)}% of the time.`;
} // the JSON is generated by ml/train.py; its inferred type is huge, so state the shape
const FEATURE_INDEX = new Map(M.features.map((f, i) => [f.toLowerCase(), i]));

/** App symptom ids → the dataset's symptom names. Symptoms with no counterpart are reported as unmapped. */
